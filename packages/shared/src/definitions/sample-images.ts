/**
 * Deterministically resolves a distinct sample photo for a slot.
 */
export function getSamplePhoto(category: string, slotIndex: number, templateIndex = 0): string {
  const catKey = category in SAMPLE_IMAGES ? (category as keyof typeof SAMPLE_IMAGES) : 'portraits';
  const list = SAMPLE_IMAGES[catKey] || SAMPLE_IMAGES.portraits;
  const idx = (slotIndex + templateIndex * 3) % list.length;
  return list[idx];
}
